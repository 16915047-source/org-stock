// Helper to render department icon cleanly
export function DepartmentIcon({ name, id, className = "w-5 h-5" }: { name?: string; id?: string; className?: string }) {
  const key = (name || id || '').toLowerCase();
  if (key.includes('วิชาการ') || key.includes('academic')) {
    return <IconAcademic className={className} />;
  }
  if (key.includes('กิจกรรม') || key.includes('activity')) {
    return <IconActivity className={className} />;
  }
  if (key.includes('สวัสดิการ') || key.includes('welfare')) {
    return <IconWelfare className={className} />;
  }
  if (key.includes('สถานที่') || key.includes('venue')) {
    return <IconVenue className={className} />;
  }
  if (key.includes('สื่อโสต') || key.includes('av')) {
    return <IconAV className={className} />;
  }
  return <IconPackage className={className} />;
}
